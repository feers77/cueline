"""genui.py <stock main_unpacked.bin> <out.S> <out.json>
Entry stubs for the UI-notify module (obj 0x0AB82D38): a requester 5/6 is served
from its shadow object p56_uiH[p-5] (index 1 inside the shadow). Each stub reads p
from the DMST (r5, or obj+0x1F94 for the two 'current request' entries), swaps r4
to the shadow when one exists, re-executes the displaced prologue and jumps back."""
import json, struct, sys

BASE = 0x08000000
CUR_WRITER = 0x083DD826   # stores the request DMST at obj+0x1F94 (read by the 'cur' entries)
# entry, mode: 'r5' = DMST in r5, 'cur' = DMST stored at obj+0x1F94
ENTRIES = [(0x083DD826, 'r5'), (0x083DD988, 'r5'), (0x083DDA8C, 'r5'), (0x083DDB8A, 'cur'),
           (0x083DDEE0, 'r5'), (0x083DE5F8, 'r5'), (0x083DE788, 'r5'), (0x083DE7EE, 'cur'),
           (0x083DEA60, 'r5'), (0x083DF3B8, 'r5'), (0x083DF91C, 'r5'), (0x083DFC1C, 'r5')]


def regs_rw(op):
    """(reads, writes) of r0..r3 for the few instruction forms allowed in a prologue."""
    n = (op >> 8) & 15; m = (op >> 4) & 15; hi = op >> 12; lo = op & 15
    if hi == 2 and lo == 6:          # mov.l Rm,@-Rn
        return {m, n}, {n}
    if hi == 4 and (op & 0xFF) in (0x22, 0x12, 0x02):   # sts.l pr/macl/mach,@-Rn
        return {n}, {n}
    if hi == 7:                      # add #imm,Rn
        return {n}, {n}
    if hi == 6 and lo == 3:          # mov Rm,Rn
        return {m}, {n}
    if hi == 0xE:                    # mov #imm,Rn
        return set(), {n}
    raise ValueError('instruction %04x not allowed in a displaced prologue' % op)


def main():
    img = open(sys.argv[1], 'rb').read()
    out = ['/* generated by genui.py -- do not edit */', '\t.section .text.ui,"ax"', '\t.align 2']
    specs = []
    for addr, mode in ENTRIES:
        need = 12 if addr % 4 == 0 else 10
        o = addr - BASE
        ops = [struct.unpack_from('<H', img, o + i)[0] for i in range(0, need, 2)]
        reads, writes = set(), set()
        for op in ops:
            r, w = regs_rw(op)
            if (r - writes) & {0, 1, 2, 3}:
                raise SystemExit('genui: %#x reads r0-r3 in the prologue' % addr)
            reads |= r; writes |= w
        jr = next(r for r in (1, 3, 2, 0) if r not in writes)
        lit_off = 8 if addr % 4 == 0 else 6
        sym = 'p56_ue_%08x' % addr
        out += ['\t.global %s' % sym, '%s:' % sym]
        if mode == 'r5':
            # p = DMST >> 24; 5/6 -> shadow (allocated on first use; none -> stock refuses 5/6)
            out += ['\tmov\tr5,r0', '\tshlr16\tr0', '\tshlr8\tr0', '\tadd\t#-5,r0', '\tmov\t#1,r2',
                    '\tcmp/hi\tr2,r0', '\tbt\t1f', '\tshll2\tr0', '\tmov.l\t8f,r2', '\tmov.l\t@(r0,r2),r2',
                    '\ttst\tr2,r2', '\tbf\t2f',
                    # p56_uiShadow(p): keeps r4-r7/pr
                    '\tsts.l\tpr,@-r15', '\tsts.l\tfpscr,@-r15', '\tmov.l\tr4,@-r15', '\tmov.l\tr5,@-r15', '\tmov.l\tr6,@-r15',
                    '\tmov.l\tr7,@-r15', '\tshlr2\tr0', '\tadd\t#5,r0', '\tmov\tr0,r4', '\tmov.l\t6f,r0',
                    '\tjsr\t@r0', '\tnop', '\tmov\tr0,r2', '\tmov.l\t@r15+,r7', '\tmov.l\t@r15+,r6',
                    '\tmov.l\t@r15+,r5', '\tmov.l\t@r15+,r4', '\tlds.l\t@r15+,fpscr', '\tlds.l\t@r15+,pr', '\ttst\tr2,r2', '\tbt\t1f',
                    '2:\tmov\tr2,r4', '\tmov.l\t3f,r0', '\tmov\tr5,r2', '\tshlr16\tr2', '\tshlr8\tr2',
                    '\tbra\t0f', '\tmov.l\tr2,@r0',
                    '1:\tmov.l\t3f,r0', '\tmov\t#0,r2', '\tmov.l\tr2,@r0', '0:']
            if addr == CUR_WRITER:
                out += ['\tmov.l\t5f,r0', '\tmov.l\tr4,@r0']
        else:
            # the 'current request' DMST obj+0x1F94 lives in whichever object the last
            # 0x083DD826 ran on (it stores it there); follow it when called with the real obj
            out += ['\tmov.l\t5f,r0', '\tmov.l\t@r0,r2', '\ttst\tr2,r2', '\tbt\t1f', '\tmov.l\t4f,r0',
                    '\tcmp/eq\tr0,r4', '\tbf\t1f', '\tmov\tr2,r4', '1:',
                    # curP = 5/6 when r4 is a shadow, else 0
                    '\tmov\t#0,r3', '\tmov.l\t8f,r2', '\tmov.l\t@r2,r0', '\tcmp/eq\tr0,r4', '\tbf\t1f',
                    '\tbra\t0f', '\tmov\t#5,r3', '1:\tmov.l\t@(4,r2),r0', '\tcmp/eq\tr0,r4', '\tbf\t0f',
                    '\tmov\t#6,r3', '0:\tmov.l\t3f,r0', '\tmov.l\tr3,@r0']
        out += ['\t.word\t0x%04x' % op for op in ops]
        out += ['\tmov.l\t7f,r%d' % jr, '\tjmp\t@r%d' % jr, '\tnop', '\t.align 2',
                '7:\t.long\t0x%08x' % (addr + need), '8:\t.long\tp56_uiH', '6:\t.long\tp56_uiShadow',
                '5:\t.long\tp56_uiCur', '4:\t.long\t0x0AB82D38',
                '3:\t.long\tp56_uiCurP']
        specs.append(dict(site=addr, end=addr + need, orig=img[o:o + need].hex(), lit_off=lit_off,
                          sym=sym, reg=1, mode=mode))
    open(sys.argv[2], 'w').write('\n'.join(out) + '\n')
    json.dump(specs, open(sys.argv[3], 'w'), indent=1)
    print('genui: %d entry stubs' % len(specs))


if __name__ == '__main__':
    main()
