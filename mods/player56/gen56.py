"""Generate the player 5/6 record stubs for the browse/DB context (re/PLAYER56_RE.md §13).

Every listed site computes a player record address as  base + m * 0x938  with
  raw: m = device number (players 1..4),  idx: m = device - 1.
The context is grown (alloc 0x26480 -> 0x28000) and players 5/6 get the records with
index 67/68, i.e. raw m 68/69, idx m 67/68 (ctx+0x26A6C, ctx+0x273A4; end ctx+0x27CDC, alloc 0x28000), past every
stock record. At each site the instructions from `mov #9,rA` up to and including
`mul.l rM,rA` (at least 10/12 bytes) are moved into a stub and replaced by a
trampoline through rA (dead there: it is about to be loaded); in the stub the mul
uses rT = table[rM] (identity except 5,6 -> 68,69 raw / 4,5 -> 67,68 idx) with rT
saved on the stack; T is never touched. Branches, branch targets, delay slots and
pc-relative loads in the moved range are refused (pc-relative mov.l/mov.w are
rewritten as absolute literals).

usage: gen56.py <stock main_unpacked.bin> <sites.txt> <out.S> <out.json>
"""
import json
import re
import struct
import sys

BASE = 0x08000000


def dec(op):
    """(text, kind, info) for the SH-4 opcodes we need to reason about."""
    n, m = (op >> 8) & 15, (op >> 4) & 15
    hi4 = op >> 12
    if hi4 == 0xE:
        return 'mov #imm,r%d' % n, 'w', n
    if hi4 == 0xD:
        return 'mov.l @(pc),r%d' % n, 'pcl', n
    if hi4 == 0x9:
        return 'mov.w @(pc),r%d' % n, 'pcw', n
    if op & 0xFF00 == 0xC700:
        return 'mova', 'mova', 0
    if hi4 in (0xA, 0xB) or op & 0xFF00 in (0x8D00, 0x8F00):
        return 'delayed branch', 'brd', None
    if op & 0xFF00 in (0x8900, 0x8B00):
        return 'branch', 'br', None
    if op & 0xF0FF in (0x0023, 0x0003, 0x402B, 0x400B) or op in (0x000B, 0x002B):
        return 'delayed branch', 'brd', None
    if op & 0xF00F == 0x0007:
        return 'mul.l r%d,r%d' % (m, n), 'mul', (m, n)
    return '%04x' % op, 'x', None


def branch_targets(img):
    t = set()
    for off in range(0x200000, 0x560000, 2):
        op = struct.unpack_from('<H', img, off)[0]
        a = BASE + off
        if op >> 12 in (0xA, 0xB):
            d = op & 0xFFF
            d = d - 0x1000 if d & 0x800 else d
            t.add(a + 4 + 2 * d)
        elif op & 0xFF00 in (0x8900, 0x8B00, 0x8D00, 0x8F00):
            d = op & 0xFF
            d = d - 0x100 if d & 0x80 else d
            t.add(a + 4 + 2 * d)
    return t


def main():
    img = open(sys.argv[1], 'rb').read()
    sites = [l.split() for l in open(sys.argv[2]) if l.strip() and not l.startswith('#')]
    targets = branch_targets(img)
    hw = lambda a: struct.unpack_from('<H', img, a - BASE)[0]
    out = ['/* generated by gen56.py -- do not edit */', '\t.section .text.sites,"ax"', '\t.align 2']
    patches = []
    for fields in sites:
        a_s, form = fields[0], fields[1]
        s = int(a_s, 16)
        treg = None
        cimm, tsuf = 9, ''
        nobt = 'nobt' in fields[2:]     # the 'branch' into the range is a literal-pool word (checked by hand)
        fields = [f for f in fields if f != 'nobt']
        for f in fields[2:]:
            if f.startswith('c=18'):          # session table (stride 0x1218: mov #18 / shll8 / add #24)
                cimm, tsuf = 18, '1218'
        fields = [f for f in fields if not f.startswith('c=')]
        if len(fields) > 2:      # secondary: the site is a later `mul.l rM,rA` reusing rA = 0x938;
            treg = int(fields[2][1:])   # rA is live there, so the trampoline goes through a given dead reg
            if hw(s) & 0xF00F != 0x0007:
                raise SystemExit('%#x: not mul.l' % s)
            rA = (hw(s) >> 8) & 15
        else:
            rA = (hw(s) >> 8) & 15
            if hw(s) & 0xF0FF != 0xE000 | cimm:
                raise SystemExit('%#x: not mov #%d,rA' % (s, cimm))
        prev = hw(s - 2)
        if dec(prev)[1] == 'brd':
            raise SystemExit('%#x: in a delay slot' % s)
        need = 12 if s % 4 == 0 else 10
        a, moved, mul = s, [], None
        while True:
            op = hw(a)
            t, kind, info = dec(op)
            if a != s and a in targets and not nobt:
                raise SystemExit('%#x: branch target %#x inside the moved range' % (s, a))
            if kind in ('br', 'brd', 'mova'):
                raise SystemExit('%#x: %s at %#x inside the moved range' % (s, t, a))
            moved.append((a, op, kind, info))
            if kind == 'mul' and info[1] == rA:
                mul = (a, info[0])
            a += 2
            if mul and a - s >= need:
                break
            if a - s > 40:
                raise SystemExit('%#x: no mul.l rM,r%d within 40 bytes' % (s, rA))
        end = a
        rM = mul[1]
        rT = next(r for r in (1, 2, 3, 4, 5, 6, 7) if r not in (rA, rM))
        if treg is not None and treg in (rA, rM):
            raise SystemExit('%#x: trampoline reg r%d is rA/rM' % (s, treg))
        tbl = ('p56_tbl_raw' if form == 'raw' else 'p56_tbl_idx') + tsuf
        lab = 'p56_s_%08x' % s
        lits = []
        body = ['\t.align 2', '%s:' % lab]
        for (ia, op, kind, info) in moved:
            if ia == mul[0]:
                body += ['\tmov.l\tr%d,@-r15' % rT, '\tmov.l\t.L%s_t,r%d' % (lab, rT),
                         '\tadd\tr%d,r%d' % (rM, rT), '\tmov.b\t@r%d,r%d' % (rT, rT),
                         '\tmul.l\tr%d,r%d' % (rT, rA), '\tmov.l\t@r15+,r%d' % rT]
            elif kind in ('pcl', 'pcw'):
                d = op & 0xFF
                if kind == 'pcl':
                    v = struct.unpack_from('<I', img, ((ia & ~3) + 4 + 4 * d) - BASE)[0]
                else:
                    v = struct.unpack_from('<h', img, (ia + 4 + 2 * d) - BASE)[0] & 0xFFFFFFFF
                k = len(lits)
                lits.append(v)
                body.append('\tmov.l\t.L%s_%d,r%d' % (lab, k, info))
            else:
                body.append('\t.short\t0x%04x\t/* %08x */' % (op, ia))
        body += ['\tmov.l\tr%d,@-r15' % rT, '\tmov.l\t.L%s_r,r%d' % (lab, rT), '\tjmp\t@r%d' % rT,
                 '\tmov.l\t@r15+,r%d' % rT, '\t.align 2',
                 '.L%s_t:\t.long\t%s' % (lab, tbl), '.L%s_r:\t.long\t0x%08x' % (lab, end)]
        body += ['.L%s_%d:\t.long\t0x%08x' % (lab, k, v) for k, v in enumerate(lits)]
        out += body
        orig = img[s - BASE:end - BASE]
        patches.append(dict(site=s, end=end, form=form, rA=rA if treg is None else treg, rM=rM, sym=lab, orig=orig.hex()))
    sess = any(any(f.startswith('c=18') for f in l[2:]) for l in sites)
    if sess:
        out += ['\t.section .rodata.tbl,"a"']
        for name, m in (('p56_tbl_raw1218', {5: 28, 6: 29}), ('p56_tbl_idx1218', {4: 27, 5: 28})):
            t = list(range(256))
            for k, v in m.items():
                t[k] = v
            out += [name + ':'] + ['\t.byte\t' + ','.join(str(x) for x in t[i:i + 32]) for i in range(0, 256, 32)]
        open(sys.argv[3], 'w').write('\n'.join(out) + '\n')
        json.dump(patches, open(sys.argv[4], 'w'), indent=1)
        print('gen56: %d session sites' % len(patches))
        return
    out += ['\t.section .rodata.tbl,"a"', 'p56_tbl_raw:']
    raw = list(range(256)); raw[5], raw[6] = 68, 69
    idx = list(range(256)); idx[4], idx[5] = 67, 68
    out += ['\t.byte\t' + ','.join(str(x) for x in raw[i:i + 32]) for i in range(0, 256, 32)]
    out += ['p56_tbl_idx:']
    out += ['\t.byte\t' + ','.join(str(x) for x in idx[i:i + 32]) for i in range(0, 256, 32)]
    open(sys.argv[3], 'w').write('\n'.join(out) + '\n')
    json.dump(patches, open(sys.argv[4], 'w'), indent=1)
    print('gen56: %d sites' % len(patches))


if __name__ == '__main__':
    main()
